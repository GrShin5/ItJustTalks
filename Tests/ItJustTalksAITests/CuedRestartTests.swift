import Testing
@testable import ItJustTalksAI

@Suite("Cued restarts")
struct CuedRestartTests {
    @Test(arguments: [
        ("封筒は14枚いや19枚用意してください", "封筒は19枚用意してください"),
        ("封筒は14枚、いや、19枚用意してください", "封筒は19枚用意してください"),
        ("午後3時やっぱり午後4時に来週の月曜いや来週の火曜に伺います", "午後4時に来週の火曜に伺います"),
        ("来週の月曜、いや、来週の火曜に伺います", "来週の火曜に伺います"),
        ("集合は10時、いや9時にします", "集合は9時にします"),
        ("120人いや80人です", "80人です"),
        ("5000円いや2万円です", "2万円です"),
        ("3.5キロいや4キロです", "4キロです"),
        ("高橋さん、いや森さんに連絡してください", "森さんに連絡してください"),
        ("会議は3時、やっぱり4時からです", "会議は4時からです"),
    ])
    func removes(_ example: (String, String)) {
        #expect(CuedRestart.collapse(example.0) == example.1)
    }

    @Test(arguments: [
        "朝じゃなくて夜の方が好きです",
        "受け取りは東倉庫じゃなくて西倉庫でお願いします",
        "問題は予算じゃなくて予定です",
        "夏はやっぱり夏祭りだよね",
        "前回と違う前提で話します",
        "これでいいや、これで決まり",
        "いや、それは違うと思います",
        "かわいいやつですね",
        "Aさんじゃなくて私が行きます",
        "集合は10時。いや、11時です",
        "遅れてすみません、10分で着きます",
    ])
    func keeps(_ text: String) {
        #expect(CuedRestart.collapse(text) == text)
    }
}
